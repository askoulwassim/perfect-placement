import { FIXTURE_TABLES } from './data.js';

const lit = (key: string, v: unknown): string => {
  if (v === null || v === undefined) return 'NULL';
  if (key.endsWith('_json')) return `'${JSON.stringify(v).replaceAll("'", "''")}'`;
  if (typeof v === 'boolean') return v ? '1' : '0';
  if (typeof v === 'number') return String(v);
  return `'${String(v).replaceAll("'", "''")}'`;
};

/** Seed SQL for the fixture data. Apply after the engine migrations. */
export function toSeedSql(): string {
  const out = ['-- Generated by packages/fixtures (pnpm --filter @perfect-placement/fixtures gen). Synthetic data only.', 'BEGIN;'];
  for (const [table, rows] of Object.entries(FIXTURE_TABLES)) {
    out.push(`\n-- ${table} (${rows.length})`);
    for (const row of rows as ReadonlyArray<Record<string, unknown>>) {
      const keys = Object.keys(row);
      out.push(`INSERT INTO ${table} (${keys.join(', ')}) VALUES (${keys.map((k) => lit(k, row[k])).join(', ')});`);
    }
  }
  out.push('COMMIT;', '');
  return out.join('\n');
}
